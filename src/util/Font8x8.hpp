// -- glyph lookup -----------------------------------------------------
// Returns a pointer to 8 rows (HEIGHT bytes), or nullptr for characters
// outside the basic ASCII range (renders as a blank advance).
inline const uint8_t *glyphFor(char c) {
  unsigned char uc = (unsigned char)c;
  if (uc > 0x7F) return nullptr;
  return GLYPHS[uc];
}

// Codepoint lookup (UTF-8 already decoded by the caller).  This font is
// ASCII-only, so anything above U+007F renders as a blank advance.
inline const uint8_t *glyphForCp(uint32_t cp) {
  if (cp > 0x7F) return nullptr;
  return GLYPHS[cp];
}

